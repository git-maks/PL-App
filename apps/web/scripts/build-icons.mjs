// Builds src/lib/icons/paths.ts from Material Symbols (Apache 2.0) — only the icons we use.
// Run: node scripts/build-icons.mjs (output is committed; the package is a dev dependency only).
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const ICONS = [
	'person', 'flag', 'qr_code_scanner', 'groups', 'explore', 'arrow_back', 'close', 'check', 'check_circle',
	'chevron_right', 'map', 'schedule', 'notifications', 'notifications_active', 'settings', 'share', 'download',
	'photo_camera', 'flashlight_on', 'flashlight_off', 'keyboard', 'search', 'school', 'science', 'location_on',
	'directions', 'info', 'lock', 'lock_open', 'star', 'logout', 'delete', 'add', 'group_add',
	'content_copy', 'refresh', 'wifi_off', 'cloud_upload', 'history', 'workspace_premium',
	'dark_mode', 'light_mode', 'open_in_new', 'edit', 'qr_code_2', 'person_add', 'help', 'timer', 'celebration',
	'menu_book', 'account_circle', 'mail', 'apartment', 'sports_soccer', 'lightbulb', 'casino', 'tune', 'bar_chart',
	'admin_panel_settings', 'play_arrow', 'stop', 'event', 'ios_share', 'add_box', 'zoom_in',
	'zoom_out', 'my_location', 'filter_list', 'arrow_forward', 'shield', 'visibility', 'public',
	'link', 'face', 'image', 'upload', 'restart_alt', 'leaderboard', 'military_tech', 'hourglass_empty', 'how_to_reg', 'campaign', 'trophy', 'keyboard_arrow_down', 'stars', 'call', 'wand_stars'
];

const dir = fileURLToPath(new URL('../node_modules/@material-symbols/svg-400/rounded/', import.meta.url));
const out = {};
for (const name of ICONS) {
	const svg = readFileSync(dir + name + '.svg', 'utf8');
	const paths = [...svg.matchAll(/<path d="([^"]+)"/g)].map((m) => m[1]);
	if (paths.length === 0) throw new Error('no path in ' + name);
	// Integer precision is plenty for a 960-unit viewBox rendered at 20–48 px and halves the size.
	out[name] = paths
		.join(' ')
		.replace(/-?\d*\.\d+/g, (n) => ' ' + Math.round(Number(n)))
		.replace(/\s+/g, ' ')
		.replace(/ -0(?![\d.])/g, ' 0');
}
const body =
	'// Generated by scripts/build-icons.mjs from Material Symbols Rounded (Apache License 2.0). Do not edit.\n' +
	'export const iconPaths = ' + JSON.stringify(out, null, '\t') + ' as const;\n\n' +
	'export type IconName = keyof typeof iconPaths;\n';
writeFileSync(fileURLToPath(new URL('../src/lib/icons/paths.ts', import.meta.url)), body);
console.log('icons:', ICONS.length);
